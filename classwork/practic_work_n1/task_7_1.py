import sched
import time

def say(text):
    # Выводим сообщение с текущим временем
    print(f"[{time.strftime('%H:%M:%S')}] {text}")

def main():
    # 1. Создаем планировщик на основе системного времени и функции sleep
    s = sched.scheduler(time.time, time.sleep)
    
    print(f"Старт. Отсчёт времени от t0")
    t0 = time.time()
    
    # 3. Запланируем 5 событий с разными задержками и приоритетами
    s.enter(0.5, 1, say, ("Прошло 0.5 секунды",))
    s.enter(1.0, 1, say, ("Прошла 1 секунда",))
    
    # Два события с одинаковым временем (2 секунды), но разным приоритетом
    s.enter(2.0, 1, say, ("Прошло 2 секунды (приоритет 1)",))
    s.enter(2.0, 0, say, ("Прошло 2 секунды (приоритет 0 — сработает ПЕРВЫМ)",))
    
    # 4. Добавляем событие через enterabs (абсолютное время запуска)
    s.enterabs(t0 + 3.0, 1, say, ("Абсолютное время t0+3 c",))
    
    # 5. Выводим размер очереди перед стартом
    print(f"Очередь до run(): {len(s.queue)} задач")
    print("run() блокирует поток, пока все задачи не выполнятся:")
    
    # Запуск выполнения очереди
    s.run()
    
    print(f"Готово. Пустая очередь? {s.empty()}")

if __name__ == '__main__':
    main()
