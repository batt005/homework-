V1 = float(input('Скорость первой машины (V1): '))
V2 = float(input('Скорость второй машины (V2): '))
S = float(input('Расстояние между машинами (S): '))
T = float(input('Время между машинами (T): '))
distance = abs(S - (V1 + V2) * T)
print(f'Расстояние между двумя машинами после времени {T} : (distance, 2)')
